"""Generate 90 days of synthetic sign-on history for Petstore Lite.

Writes data/seed/signon_history.sql: extra customer accounts and SIGNON_AUDIT
events that follow the application rules (3 failures in a row lock an account,
PSL_ACCT_UNLOCK clears the lock 30+ minutes later, a sign-on usually ends in a
sign-off). Deterministic: the same seed gives the same file.

Usage: python3 data/generate_history.py [end-date YYYY-MM-DD]
"""
import random
import sys
from datetime import datetime, timedelta
from pathlib import Path

SEED = 1302
DAYS = 90
GIVEN = ["al", "bea", "cal", "dee", "eli", "fay", "gus", "hal", "ida", "jo", "kai", "lu",
         "max", "ned", "ola", "pam", "quin", "ray", "sue", "ted", "uma", "vic", "wes", "zoe"]
FAMILY = ["tan", "lim", "ng", "lee", "wong", "chan", "kumar", "smith", "brown", "jones",
          "garcia", "ito", "sato", "khan", "nair", "ong", "teo", "goh", "koh", "das"]


def main():
    rnd = random.Random(SEED)
    end = datetime.strptime(sys.argv[1], "%Y-%m-%d") if len(sys.argv) > 1 else datetime(2026, 10, 30)
    start = end - timedelta(days=DAYS)
    out = Path(__file__).parent / "seed" / "signon_history.sql"
    out.parent.mkdir(exist_ok=True)

    users = {}
    while len(users) < 40:
        name = rnd.choice(GIVEN) + rnd.choice(["", ".", "_"]) + rnd.choice(FAMILY)
        if rnd.random() < 0.35:
            name += str(rnd.randint(1, 99))
        if name in users or not (3 <= len(name) <= 25):
            continue
        created = start + timedelta(days=rnd.randint(0, DAYS - 10), minutes=rnd.randint(480, 1320))
        users[name] = {"created": created, "pw": "pw" + str(rnd.randint(1000, 9999)),
                       "ip": "10.%d.%d.%d" % (rnd.randint(1, 40), rnd.randint(0, 255), rnd.randint(2, 254))}
    for seeded in ("j2ee", "shopper", "admin"):
        users[seeded] = {"created": None, "pw": None, "ip": "10.0.0.%d" % rnd.randint(2, 254)}

    events = []  # (ts, user, type, addr)
    accounts = {}  # final state per created user
    for name, u in users.items():
        if u["created"]:
            events.append((u["created"], name, "USER_CREATED", u["ip"]))
            accounts[name] = {"failed": 0, "locked": "N", "locked_ts": None, "last": u["created"]}
        first = u["created"] or start
        day = first
        while day < end:
            day += timedelta(days=rnd.choice([1, 1, 2, 3, 4, 7]))
            if day >= end:
                break
            ts = day.replace(hour=rnd.randint(7, 22), minute=rnd.randint(0, 59), second=rnd.randint(0, 59))
            ip = u["ip"] if rnd.random() < 0.8 else "10.%d.%d.%d" % (rnd.randint(1, 40), rnd.randint(0, 255), rnd.randint(2, 254))
            fails = 0
            r = rnd.random()
            if r < 0.12:
                fails = 1
            elif r < 0.16:
                fails = 2
            elif r < 0.19:
                fails = 3
            for _ in range(fails):
                events.append((ts, name, "SIGNON_FAIL", ip))
                ts += timedelta(seconds=rnd.randint(8, 60))
            if fails == 3:
                events.append((ts, name, "ACCOUNT_LOCKED", ip))
                if rnd.random() < 0.5:
                    events.append((ts + timedelta(minutes=rnd.randint(2, 20)), name, "SIGNON_LOCKED", ip))
                unlock = ts + timedelta(minutes=30)
                unlock = unlock + timedelta(minutes=15 - unlock.minute % 15, seconds=-unlock.second)
                events.append((unlock, name, "ACCOUNT_UNLOCKED", "batch:PSL_ACCT_UNLOCK"))
                ts = unlock + timedelta(minutes=rnd.randint(5, 240))
            events.append((ts, name, "SIGNON_OK", ip))
            if name in accounts:
                accounts[name]["last"] = ts
            if rnd.random() < 0.7:
                events.append((ts + timedelta(minutes=rnd.randint(2, 15)), name, "SIGNOFF", ip))

    # two accounts end the period locked and waiting for the unlock job
    for name in rnd.sample(sorted(accounts), 2):
        ts = end - timedelta(minutes=rnd.randint(5, 25))
        ip = users[name]["ip"]
        for i in range(3):
            events.append((ts + timedelta(seconds=20 * i), name, "SIGNON_FAIL", ip))
        events.append((ts + timedelta(seconds=60), name, "ACCOUNT_LOCKED", ip))
        accounts[name].update(failed=3, locked="Y", locked_ts=ts + timedelta(seconds=60))

    events.sort()
    q = lambda v: "NULL" if v is None else "'%s'" % v
    t = lambda d: "NULL" if d is None else "'%s'" % d.strftime("%Y-%m-%d %H:%M:%S")
    with out.open("w") as f:
        f.write("-- Generated by data/generate_history.py (seed %d). %d accounts, %d audit events, %s to %s.\n"
                % (SEED, len(accounts), len(events), start.date(), end.date()))
        f.write("-- Load after the first populate: ij data/seed/signon_history.sql\nAUTOCOMMIT OFF;\n\n")
        for name in sorted(accounts):
            a = accounts[name]
            f.write("INSERT INTO signon (username, password, role, failed_attempts, locked, locked_ts, last_signon, created_ts) "
                    "VALUES (%s, %s, 'CUSTOMER', %d, %s, %s, %s, %s);\n"
                    % (q(name), q(users[name]["pw"]), a["failed"], q(a["locked"]), t(a["locked_ts"]), t(a["last"]), t(users[name]["created"])))
        last_ok = {}
        for ts, name, typ, ip in events:
            if typ == "SIGNON_OK":
                last_ok[name] = ts
        for name in ("j2ee", "shopper", "admin"):
            f.write("UPDATE signon SET created_ts = %s, last_signon = %s WHERE username = '%s';\n"
                    % (t(start), t(last_ok.get(name)), name))
        f.write("\n")
        for ts, name, typ, ip in events:
            f.write("INSERT INTO signon_audit (username, event_type, event_ts, remote_addr) VALUES (%s, '%s', %s, %s);\n"
                    % (q(name), typ, t(ts), q(ip)))
        f.write("\nCOMMIT;\n")
    print("wrote %s: %d accounts, %d events" % (out, len(accounts), len(events)))


if __name__ == "__main__":
    main()
